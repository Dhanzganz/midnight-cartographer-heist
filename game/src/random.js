// random.js — a tiny deterministic seeded RNG (mulberry32).
//
// The whole museum is laid out and animated from one seed, so a staged scene
// (title, cover, chase, vault) looks the same on every load and the headless
// self-test can reason about the world.

export function mulberry32(seed) {
  let a = seed >>> 0;
  return function next() {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** A fresh RNG stream for one run of the game. */
export function makeRng(seed) {
  const next = mulberry32(seed);
  return {
    next,
    range(min, max) {
      return min + next() * (max - min);
    },
    int(min, max) {
      return Math.floor(min + next() * (max - min + 1));
    },
    pick(list) {
      return list[Math.floor(next() * list.length)];
    },
    chance(p) {
      return next() < p;
    },
  };
}

/** The one seed the shipped scenes and sparkle fields are built from. */
export const WORLD_SEED = 20261122;
